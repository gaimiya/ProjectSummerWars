-- 月次集計（1人×1か月）。社労士に渡すCSVの元。時間はすべて分
CREATE TABLE monthly_record (
  id                    BIGSERIAL PRIMARY KEY,
  target_month          VARCHAR(7)   NOT NULL,
  employee_no           VARCHAR(10)  NOT NULL,
  employee_name         VARCHAR(50),
  department            VARCHAR(50),
  employment_type       VARCHAR(20),
  pay_type              VARCHAR(10),
  base_salary           INTEGER      NOT NULL DEFAULT 0,
  standard_minutes      INTEGER      NOT NULL DEFAULT 480,
  work_days             INTEGER      NOT NULL DEFAULT 0,
  work_minutes          INTEGER      NOT NULL DEFAULT 0,
  overtime_minutes      INTEGER      NOT NULL DEFAULT 0,
  night_minutes         INTEGER      NOT NULL DEFAULT 0,
  saturday_minutes      INTEGER      NOT NULL DEFAULT 0,
  holiday_minutes       INTEGER      NOT NULL DEFAULT 0,
  holiday_night_minutes INTEGER      NOT NULL DEFAULT 0,
  paid_leave_days       DOUBLE PRECISION NOT NULL DEFAULT 0,
  special_leave_days    DOUBLE PRECISION NOT NULL DEFAULT 0,
  commute_allowance     INTEGER      NOT NULL DEFAULT 0,
  housing_allowance     INTEGER      NOT NULL DEFAULT 0,
  fixed_allowance       INTEGER      NOT NULL DEFAULT 0,
  fixed_allowance_name  VARCHAR(50),
  incentive             INTEGER      NOT NULL DEFAULT 0,
  incentive_detail      VARCHAR(500),
  transport_expense     INTEGER      NOT NULL DEFAULT 0,
  other_expense         INTEGER      NOT NULL DEFAULT 0,
  status                VARCHAR(10)  NOT NULL DEFAULT '集計済み',
  collected_at          TIMESTAMP,
  collect_count         INTEGER      NOT NULL DEFAULT 0,
  sheet_url             VARCHAR(255),
  CONSTRAINT uq_monthly UNIQUE (target_month, employee_no)
);
